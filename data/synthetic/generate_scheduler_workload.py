"""Write one synthetic scheduler workload to CSV for inspection.

Usage (from the repository root)::

    python data/synthetic/generate_scheduler_workload.py --load medium --seed 0 --out w.csv
    python data/synthetic/generate_scheduler_workload.py --load heavy --seed 0 --out llm.csv \\
        --config configs/scheduler_llm_workload.yaml

The workload is generated by :func:`src.scheduler.tasks.generate_workload` with the
``workload:`` block of ``configs/scheduler_ddqn.yaml``, or of the workload profile given with
``--config`` (the second line writes the LLM-style mix of inference requests and fine-tuning
jobs); every distribution is ``[Assumption — not in paper]``. Generated CSV files are
git-ignored.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:  # allow running the file directly, not only with -m
    sys.path.insert(0, str(REPO_ROOT))

from src.common.io import write_csv  # noqa: E402
from src.common.logging_utils import get_logger, setup_logging  # noqa: E402
from src.scheduler.config import load_scheduler_config  # noqa: E402
from src.scheduler.tasks import WORKLOAD_CSV_FIELDS, generate_workload, workload_rows  # noqa: E402

LOGGER = get_logger("data.synthetic.generate_scheduler_workload")


def main(argv: list[str] | None = None) -> Path:
    """Generate the workload and write it; return the CSV path."""
    parser = argparse.ArgumentParser(description="Write one scheduler workload to CSV.")
    parser.add_argument("--config", default=str(REPO_ROOT / "configs" / "scheduler_ddqn.yaml"))
    parser.add_argument("--load", required=True, help="load profile, e.g. light/medium/heavy")
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--smoke", action="store_true")
    parser.add_argument("--set", dest="overrides", action="append", default=[])
    args = parser.parse_args(argv)
    setup_logging("INFO")
    cfg = load_scheduler_config(args.config, overrides=args.overrides, smoke=args.smoke)
    tasks = generate_workload(cfg.workload, args.load, args.seed)
    path = write_csv(args.out, workload_rows(tasks), WORKLOAD_CSV_FIELDS)
    total_cpu = sum(t.total_cpu_ms for t in tasks)
    span = max(t.arrival_ms for t in tasks)
    LOGGER.info("%d tasks, total CPU %.1f ms, arrival span %.1f ms -> %s",
                len(tasks), total_cpu, span, path)  # fmt: skip
    return path


if __name__ == "__main__":
    main()
